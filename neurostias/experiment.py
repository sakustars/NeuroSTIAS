"""Experiment harness used by experiments/E*/run.py.

* results go to experiments/<id>/results/ (tables, figures, summary.json, provenance.json)
* REPORT.md is generated from summary.json and the tables, never written by hand
* baselines that fail to install or run are recorded in summary["baseline_status"]
  rather than silently dropped
"""

from __future__ import annotations

import json
import subprocess
import sys
import time
import traceback
from pathlib import Path

import numpy as np
import pandas as pd

from .core.provenance import Provenance, write_json

ROOT = Path(__file__).resolve().parents[1]
BASELINE_PY = ROOT / "benchmarks" / "envs" / "baselines" / "bin" / "python"


class Experiment:
    def __init__(self, eid: str, title: str, question: str, data_origin: str = "real", params: dict | None = None,
                 seeds: list[int] | None = None):
        self.eid, self.title, self.question = eid, title, question
        self.dir = next(ROOT.joinpath("experiments").glob(f"{eid}_*"))
        self.res = self.dir / "results"
        self.res.mkdir(parents=True, exist_ok=True)
        self.seeds = seeds or [0, 1, 2, 3, 4]
        self.params = params or {}
        self.prov = Provenance("experiment", eid, params={**self.params, "seeds": self.seeds}, data_origin=data_origin)
        self.summary: dict = {"id": eid, "title": title, "question": question, "data_origin": data_origin,
                              "baseline_status": {}, "notes": []}
        self.t0 = time.time()

    # ------------------------------------------------------------------ outputs
    def table(self, df: pd.DataFrame, name: str, index: bool = False) -> Path:
        p = self.res / name
        df.to_csv(p, index=index)
        return p

    def figure(self, fig, name: str) -> Path:
        import matplotlib.pyplot as plt
        p = self.res / name
        fig.savefig(p, dpi=250, bbox_inches="tight")
        fig.savefig(p.with_suffix(".pdf"), bbox_inches="tight")
        plt.close(fig)
        return p

    def note(self, text: str) -> None:
        self.summary["notes"].append(text)

    def baseline(self, name: str, status: str, detail: str = "") -> None:
        self.summary["baseline_status"][name] = {"status": status, "detail": detail[-2000:]}

    def finish(self, report_sections: list[tuple[str, str]] | None = None) -> None:
        self.summary["runtime_seconds"] = round(time.time() - self.t0, 1)
        write_json(self.summary, self.res / "summary.json")
        self.prov.write(self.res, extra={"summary_file": "summary.json"})
        self._report(report_sections or [])

    def _report(self, sections):
        s = self.summary
        lines = [f"# {s['id']}: {s['title']}", "", f"**Question.** {s['question']}", "",
                 f"*Data origin: {s['data_origin']}. This file is generated by `run.py` from `results/`; do not edit by hand.*",
                 ""]
        for head, body in sections:
            lines += [f"## {head}", "", body, ""]
        if s["baseline_status"]:
            lines += ["## Baseline status", "", "| baseline | status | detail |", "|---|---|---|"]
            for k, v in s["baseline_status"].items():
                d = v["detail"].replace("\n", " ")[:200]
                lines.append(f"| {k} | {v['status']} | {d} |")
            lines.append("")
        if s["notes"]:
            lines += ["## Notes and limitations", ""] + [f"- {n}" for n in s["notes"]] + [""]
        lines += [f"Runtime: {s['runtime_seconds']} s. Provenance: `results/provenance.json`."]
        (self.dir / "REPORT.md").write_text("\n".join(lines))


def run_baseline_script(script: Path, args: list[str], timeout: int = 7200, env: str = "baselines") -> tuple[bool, str]:
    """Run a baseline wrapper in an isolated environment under benchmarks/envs/<env>."""
    py = ROOT / "benchmarks" / "envs" / env / "bin" / "python"
    if not py.exists():
        return False, f"baseline environment not installed (benchmarks/envs/{env})"
    try:
        r = subprocess.run([str(py), str(script), *args], capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return False, f"timeout after {timeout}s"
    return r.returncode == 0, (r.stdout[-3000:] + "\n" + r.stderr[-3000:])


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v) for v in r.values]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)
